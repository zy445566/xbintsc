/**
 * Compile-time storage configuration for the `storage` extension.
 *
 * The project config's `storage` object (memory vs file, plus the resolved
 * database path) is embedded into the binary as a small linkable object, the
 * same way the application icon is (see `icon.ts`). The storage runtime reads
 * these symbols when it opens its database, so a project can choose between an
 * in-memory database (the default) and a persistent file without any runtime
 * lookup.
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { hashParts } from "./cache.js";
import { compileC, sysrootFlags, type Runner } from "./toolchain.js";
import type { StorageConfig } from "./config.js";

/** The C symbols the embedded storage configuration exposes. */
export const STORAGE_SYMBOLS = {
  backend: "xt_storage_backend",
  path: "xt_storage_path",
  pathLen: "xt_storage_path_len",
} as const;

/** The storage backend after config defaults and path resolution. */
export interface ResolvedStorage {
  readonly backend: "memory" | "file";
  /** Absolute database path; empty for the memory backend. */
  readonly path: string;
}

/** Normalise a (possibly undefined) config into a concrete backend + path. */
export function resolveStorage(config: StorageConfig | undefined): ResolvedStorage {
  if (config?.backend === "file") return { backend: "file", path: config.path ?? "" };
  return { backend: "memory", path: "" };
}

/** Generate the C translation unit embedding the storage backend + path. */
export function storageSource(storage: ResolvedStorage): string {
  const backend = storage.backend === "file" ? 1 : 0;
  /* The path is emitted as raw UTF-8 bytes plus a trailing NUL, so a path that
   * contains `\`, `"` or non-ASCII characters needs no escaping. */
  const path = storage.backend === "file" ? Buffer.from(storage.path, "utf8") : Buffer.alloc(0);
  const bytes = [...path, 0x00];
  const lines: string[] = [];
  for (let offset = 0; offset < bytes.length; offset += 16) {
    const chunk = Array.from(bytes.slice(offset, offset + 16), (byte) => `0x${byte.toString(16).padStart(2, "0")}`);
    lines.push("  " + chunk.join(", ") + ",");
  }
  if (lines.length === 0) lines.push("  0x00,");
  return [
    "/* Generated by xbintsc - embedded storage configuration. Do not edit. */",
    `const unsigned int ${STORAGE_SYMBOLS.backend} = ${backend}u;`,
    `const unsigned char ${STORAGE_SYMBOLS.path}[] = {`,
    ...lines,
    "};",
    `const unsigned long long ${STORAGE_SYMBOLS.pathLen} = ${path.length}ull;`,
    "",
  ].join("\n");
}

/**
 * Compile the storage configuration into an object exposing
 * {@link STORAGE_SYMBOLS}. Cached by the backend + path, so an unchanged
 * configuration is never recompiled.
 */
export function ensureStorageObject(
  runner: Runner,
  clang: string,
  cacheDir: string,
  storage: ResolvedStorage,
  env?: Record<string, string>,
  sdkRoot?: string,
): string {
  const key = hashParts(["storage", process.platform, storage.backend, storage.path]);
  const sourcePath = join(cacheDir, `storage-${key}.c`);
  const objectPath = join(cacheDir, `storage-${key}.o`);
  if (!existsSync(objectPath)) {
    mkdirSync(cacheDir, { recursive: true });
    writeFileSync(sourcePath, storageSource(storage));
    compileC(runner, clang, sourcePath, objectPath, cacheDir, env, sysrootFlags(sdkRoot));
  }
  return objectPath;
}
