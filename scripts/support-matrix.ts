#!/usr/bin/env node
/**
 * Render `doc/support-matrix.md` and its Chinese mirror from the conformance
 * corpus.
 *
 * The corpus is executable evidence: `tests/conformance/` compiles every
 * supported case and compares its output with Node, and requires every
 * unsupported case to fail with the listed diagnostic code. This script turns
 * the same catalogue into the human-readable table, so the document cannot
 * claim a feature the tests do not exercise.
 *
 * Usage: npm run docs:matrix
 */

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  SUPPORT_AREAS,
  SUPPORTED_CASES,
  UNSUPPORTED_CASES,
  type SupportArea,
} from "../tests/conformance/corpus.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

type Language = "en" | "zh";

export const MATRIX_FILES: Readonly<Record<Language, string>> = {
  en: "doc/support-matrix.md",
  zh: "doc/zh-CN/support-matrix.md",
};

function docLink(area: SupportArea, language: Language): string {
  const relative = area.doc.startsWith("doc/") ? area.doc.slice("doc/".length) : area.doc;
  return language === "en" ? relative : `../${relative}`;
}

function areaTitle(area: SupportArea, language: Language): string {
  return language === "en" ? area.title : area.titleZh;
}

function count(area: SupportArea, cases: readonly { readonly area: string }[]): number {
  return cases.filter((testCase) => testCase.area === area.id).length;
}

function rowsFor(language: Language): string {
  return SUPPORT_AREAS.map((area) => {
    const supported = count(area, SUPPORTED_CASES);
    const unsupported = count(area, UNSUPPORTED_CASES);
    return `| ${areaTitle(area, language)} | ${supported} | ${unsupported} | [${language === "en" ? "reference" : "参考"}](${docLink(area, language)}) |`;
  }).join("\n");
}

function supportedTable(language: Language): string {
  const header =
    language === "en"
      ? "| Case | Area | What it pins down |\n| --- | --- | --- |"
      : "| 用例 | 领域 | 固化的行为 |\n| --- | --- | --- |";
  const rows = SUPPORTED_CASES.map((testCase) => {
    const area = SUPPORT_AREAS.find((candidate) => candidate.id === testCase.area)!;
    const claim = language === "en" ? testCase.claim : testCase.claimZh;
    return `| \`${testCase.name}\` | ${areaTitle(area, language)} | ${claim} |`;
  });
  return [header, ...rows].join("\n");
}

function unsupportedTable(language: Language): string {
  const header =
    language === "en"
      ? "| Case | Area | Diagnostic | Why |\n| --- | --- | ---: | --- |"
      : "| 用例 | 领域 | 诊断码 | 原因 |\n| --- | --- | ---: | --- |";
  const rows = UNSUPPORTED_CASES.map((testCase) => {
    const area = SUPPORT_AREAS.find((candidate) => candidate.id === testCase.area)!;
    const claim = language === "en" ? testCase.claim : testCase.claimZh;
    return `| \`${testCase.name}\` | ${areaTitle(area, language)} | TS${testCase.code} | ${claim} |`;
  });
  return [header, ...rows].join("\n");
}

export function renderSupportMatrix(language: Language): string {
  const corpusLink =
    language === "en" ? "../tests/conformance/corpus.ts" : "../../tests/conformance/corpus.ts";
  const testLink =
    language === "en" ? "../tests/conformance/conformance.test.ts" : "../../tests/conformance/conformance.test.ts";

  if (language === "en") {
    return `# Support matrix

> Language: **English** | [简体中文](./zh-CN/support-matrix.md)

> **Generated** by \`npm run docs:matrix\` from the executable corpus in
> [\`tests/conformance/corpus.ts\`](${corpusLink}). Do not edit this file by
> hand: change a case and regenerate.

Every supported case is compiled by xbintsc and run under Node; the
[conformance suite](${testLink}) asserts byte-identical stdout. Every
unsupported case must fail with the listed diagnostic code. Because the suite
runs on every CI platform, this table cannot claim more than the compiler does.

## Coverage by area

| Area | Supported | Unsupported | Reference |
| --- | ---: | ---: | --- |
${rowsFor(language)}

## Supported cases (differential against Node)

${supportedTable(language)}

## Unsupported cases (expected diagnostics)

${unsupportedTable(language)}
`;
  }

  return `# 支持矩阵

> 语言：[English](../support-matrix.md) | **简体中文**

> 本文件由 \`npm run docs:matrix\` 根据可执行语料
> [\`tests/conformance/corpus.ts\`](${corpusLink}) 生成，请勿手工编辑：
> 修改用例后重新生成。

每个“支持”用例都会由 xbintsc 编译并在 Node 下运行，
[一致性测试](${testLink}) 断言两者 stdout 逐字节相同；每个“不支持”用例
必须以表中列出的诊断码失败。该测试在 CI 的每个平台运行，因此本表不会
声称编译器做不到的能力。

## 各领域覆盖

| 领域 | 支持 | 不支持 | 参考 |
| --- | ---: | ---: | --- |
${rowsFor(language)}

## 支持的用例（与 Node 对比）

${supportedTable(language)}

## 不支持的用例（预期诊断）

${unsupportedTable(language)}
`;
}

function main(): void {
  for (const language of ["en", "zh"] as const) {
    const path = resolve(root, MATRIX_FILES[language]);
    writeFileSync(path, renderSupportMatrix(language));
    process.stdout.write(`xbintsc: wrote ${MATRIX_FILES[language]}\n`);
  }
}

if (process.argv[1] !== undefined && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main();
}
